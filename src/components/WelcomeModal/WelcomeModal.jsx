export default function WelcomeModal({ isOpen, onClose, firstname }) {
    const { start: startTutorial } = useTutorial();

    useEffect(() => {
        if (!isOpen) return;
        const handleKey = (e) => { if (e.key === 'Escape') onClose(); };
        document.addEventListener('keydown', handleKey);
        return () => document.removeEventListener('keydown', handleKey);
    }, [isOpen, onClose]);

    useEffect(() => {
        document.body.style.overflow = isOpen ? 'hidden' : '';
        return () => { document.body.style.overflow = ''; };
    }, [isOpen]);

    if (!isOpen) return null;

    function handleStartTutorial() {
        onClose();
        startTutorial();
    }

    return (
        <div className={styles.backdrop} onClick={onClose} role="dialog" aria-modal="true" aria-label="Welcome to SlotMeIn">
            <div className={styles.panel} onClick={(e) => e.stopPropagation()}>

                {/* Hero */}
                <div className={styles.hero}>
                    <button className={styles.closeBtn} onClick={onClose} aria-label="Close">
                        <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round">
                            <line x1="18" y1="6" x2="6" y2="18" />
                            <line x1="6" y1="6" x2="18" y2="18" />
                        </svg>
                    </button>
                    <div className={styles.brand}>SlotMeIn</div>
                    <h1 className={styles.heading}>
                        Welcome aboard{firstname ? `, ${firstname}` : ''}!
                    </h1>
                    <p className={styles.subheading}>
                        You're all set up. Here's how to build your first schedule in five steps.
                    </p>
                </div>

                {/* Steps */}
                <div className={styles.body}>
                    <div className={styles.steps}>
                        {STEPS.map((step) => (
                            <div key={step.number} className={styles.step}>
                                <div className={styles.stepNumber}>{step.number}</div>
                                <div className={styles.stepIcon}>{step.icon}</div>
                                <div className={styles.stepContent}>
                                    <h3 className={styles.stepTitle}>{step.title}</h3>
                                    <p className={styles.stepDesc}>{step.description}</p>
                                </div>
                            </div>
                        ))}
                    </div>

                    <div className={styles.footer}>
                        <button className={styles.skipBtn} onClick={onClose}>
                            Explore on my own
                        </button>
                        <button className={styles.startBtn} onClick={handleStartTutorial}>
                            Take the tour
                            <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round" strokeLinejoin="round">
                                <line x1="5" y1="12" x2="19" y2="12" />
                                <polyline points="12 5 19 12 12 19" />
                            </svg>
                        </button>
                    </div>
                </div>
            </div>
        </div>
    );
}
